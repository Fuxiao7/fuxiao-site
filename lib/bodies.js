export function articleFor(slug) {
  const post = posts.find((p) => p.slug === slug) || posts[0];
  if (post.slug === "p0") {
    return { ...post, deck: p0.deck, blocks: p0.blocks };
  }
  const extra = bodies[post.slug];
  return {
    ...post,
    deck: extra?.deck || post.excerpt,
    blocks: [{ t: "p", text: post.excerpt }, ...(extra?.blocks || [])],
  };
}

export const postIndex = (slug) => posts.findIndex((p) => p.slug === slug);
